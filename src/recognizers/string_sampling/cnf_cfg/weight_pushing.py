import dataclasses
import math
import random
from collections.abc import Callable, Iterable, Sequence
from typing import cast

import torch
import numpy

from recognizers.tools.linked_list import LinkedList
from recognizers.theory.symbol import Symbol
from recognizers.theory.grammar import Variable, Terminal
from recognizers.theory.cnf_cfg import ChomskyNormalFormContextFreeGrammar
from recognizers.theory.cnf_wcfg import (
    ChomskyNormalFormWeightedContextFreeGrammar,
    TerminalRule,
    BinaryRule
)
from recognizers.theory.cnf_wcfg_allsum import cnf_wcfg_partition
from recognizers.theory.cnf_cfg_generates import PyTorchChomskyNormalFormContextFreeGrammarMembershipTester
from recognizers.theory.log_binning_semiring import LogBinningSemiring

@dataclasses.dataclass
class TerminalDistribution:
    terminals: list[Terminal]
    cumulative_weights: numpy.ndarray

@dataclasses.dataclass
class BinaryRuleDistribution:
    rules: list[tuple[Variable, Variable]]
    cumulative_weights: list[numpy.ndarray]

    def get_cumulative_weights_for_length(self, length: int) -> numpy.ndarray:
        assert 0 <= length - 2 < len(self.cumulative_weights)
        return self.cumulative_weights[length - 2]

class ChomskyNormalFormWeightedContextFreeGrammarSampler:

    _indexed_cnf_cfg: PyTorchChomskyNormalFormContextFreeGrammarMembershipTester
    _terminal_distributions: dict[Variable, TerminalDistribution]
    _binary_rule_distributions: dict[Variable, BinaryRuleDistribution]
    _valid_lengths: torch.Tensor

    def __init__(self,
        cnf_cfg: ChomskyNormalFormContextFreeGrammar,
        cnf_wcfg: ChomskyNormalFormWeightedContextFreeGrammar,
        dtype: torch.dtype,
        device: torch.device
    ) -> None:
        super().__init__()
        semiring = cnf_wcfg.semiring()
        if not isinstance(semiring, LogBinningSemiring):
            raise TypeError
        # Index the CFG for efficient CKY parsing.
        self._indexed_cnf_cfg = PyTorchChomskyNormalFormContextFreeGrammarMembershipTester(cnf_cfg, device)
        # Precompute the probabilities of sampling each terminal conditioned on
        # the current variable and a target length of 1.
        grouped_terminal_rules: dict[Variable, list[TerminalRule]] = {}
        for terminal_rule in cnf_wcfg.terminal_rules():
            grouped_terminal_rules.setdefault(terminal_rule.left, []).append(terminal_rule)
        self._terminal_distributions = {}
        for left, terminal_rule_list in grouped_terminal_rules.items():
            # Convert the log weights to probabilities using softmax, then
            # compute their cumulative sum.
            terminal_rule_weights = torch.stack([
                terminal_rule.weight[1]
                for terminal_rule in terminal_rule_list
            ])
            terminal_rule_weights = torch.softmax(terminal_rule_weights, dim=0)
            terminal_rule_weights.cumsum_(dim=0)
            self._terminal_distributions[left] = TerminalDistribution(
                terminals=[terminal_rule.terminal for terminal_rule in terminal_rule_list],
                cumulative_weights=terminal_rule_weights.cpu().numpy().copy()
            )
        # Precompute the probabilities of sampling each rule and split point
        # conditioned on the current variable and target length. Do this by
        # performing weight pushing in the log binning semiring over the WCFG.
        # The first step is to compute the partition function (total weight of
        # all strings generated by each variable) using fixed point iteration.
        log_partition_function = cnf_wcfg_partition(cnf_wcfg, dtype, device)
        # Group rules by their left sides and precompute the cumulative sums of
        # the probabilities of sampling each rule and split point conditioned on
        # target length.
        max_length = log_partition_function.size(-1) - 1
        grouped_binary_rules: dict[Variable, list[BinaryRule]] = {}
        for binary_rule in cnf_wcfg.binary_rules():
            grouped_binary_rules.setdefault(binary_rule.left, []).append(binary_rule)
        self._binary_rule_distributions = {}
        for left, binary_rule_list in grouped_binary_rules.items():
            # rule_log_weights : len(binary_rule_list)
            rule_log_weights = torch.stack([
                binary_rule.weight[0]
                for binary_rule in binary_rule_list
            ])
            # B_log_weights : (max_length-1) x len(binary_rule_list)
            B_list = [
                cnf_wcfg.zero_indexed(binary_rule.first)
                for binary_rule in binary_rule_list
            ]
            B_log_weights = log_partition_function[B_list, 1:max_length].permute(1, 0)
            # C_index : (max_length-1) x (max_length-1)
            C_index = torch.arange(1, max_length)[:, None] - torch.arange(max_length-1)[None, :]
            # C_log_weights : (max_length-1) x (max_length-1) x len(binary_rule_list)
            C_list = [
                cnf_wcfg.zero_indexed(binary_rule.second)
                for binary_rule in binary_rule_list
            ]
            C_log_weights = log_partition_function[C_list][:, C_index].permute(1, 2, 0)
            # Use broadcasting to compute all possible log weights in parallel.
            # The dimensions are:
            #     0: target length, from 2 to max_length
            #     1: length of B, from 1 to max_length - 1
            #     2: rules with A on left side
            # This computes a lot of useless log weights where (length of B) >=
            # (target length), but we will mask them out.
            # all_weights : (max_length-1) x (max_length-1) x len(binary_rule_list)
            all_weights = rule_log_weights[None, None, :] + (B_log_weights[None, :, :] + C_log_weights)
            del B_log_weights
            del C_log_weights
            # Mask out all the useless weights with -inf so they won't count in
            # the softmax.
            all_weights[C_index < 1] = -math.inf
            del C_index
            # Flatten the B length and rule dimensions.
            all_weights = torch.flatten(all_weights, 1)
            # Convert the log weights to probabilities for each target length
            # using softmax.
            all_weights = torch.softmax(all_weights, dim=1)
            # Compute the cumulative sum of the probabilities for each target
            # length for efficient sampling later.
            all_weights.cumsum_(dim=1)
            # Now that we have a big, rectangular tensor with a bunch of useless
            # entries, slice out only the useful entries and store them as a
            # separate array of cumulative probabilities for each target length.
            cumulative_weights: list[numpy.ndarray] = []
            num_rules = len(binary_rule_list)
            for length in range(2, max_length+1):
                cumulative_weights.append(all_weights[length-2, :(length-1)*num_rules].cpu().numpy().copy())
            del all_weights
            self._binary_rule_distributions[left] = BinaryRuleDistribution(
                rules=[binary_rule.right for binary_rule in binary_rule_list],
                cumulative_weights=cumulative_weights
            )
        # Figure out which lengths are valid by looking at which entries of the
        # allsum are not -inf.
        log_binning_allsum = log_partition_function[cnf_cfg.zero_indexed(cnf_cfg.start_variable())]
        self._valid_lengths = (log_binning_allsum > -math.inf).cpu()

    def set_cky_device(self, device: torch.device) -> None:
        self._indexed_cnf_cfg.set_device(device)

    def alphabet_size(self) -> int:
        return self._indexed_cnf_cfg.num_terminals()

    def max_length(self) -> int:
        return self._valid_lengths.size(0) - 1

    def valid_lengths(self, count_range: tuple[int, int]) -> list[int]:
        lo, hi = count_range
        return [
            length
            for length, is_valid in zip(
                range(lo, hi+1),
                self._valid_lengths[lo:hi+1].tolist(),
                strict=True
            )
            if is_valid
        ]

    def is_valid_length(self, length: int) -> bool:
        return cast(bool, self._valid_lengths[length].item())

    def generates(self, string: Iterable[Symbol]) -> bool:
        return self._indexed_cnf_cfg.generates(string)

    def sample(self,
        length: int,
        generator: random.Random
    ) -> Iterable[Terminal]:
        if length == 0:
            if not self._indexed_cnf_cfg.has_empty_rule():
                raise ValueError
            # The length 0 case is only possible when the CFG has an
            # S -> epsilon rule.
            return []
        else:
            return self.sample_from_variable(
                self._indexed_cnf_cfg.start_variable(),
                length,
                generator
            )

    def sample_from_variable(self,
        A: Variable,
        length: int,
        generator: random.Random
    ) -> LinkedList[Terminal]:
        if length == 1:
            # If the target length is 1, our only choice is to sample a
            # terminal.
            terminal_distribution = self._terminal_distributions[A]
            terminal, = generator.choices(
                terminal_distribution.terminals,
                cum_weights=cast(Sequence[float], terminal_distribution.cumulative_weights)
            )
            return LinkedList([terminal])
        else:
            binary_rule_distribution = self._binary_rule_distributions[A]
            cum_weights = binary_rule_distribution.get_cumulative_weights_for_length(length)
            index, = generator.choices(
                range(len(cum_weights)),
                cum_weights=cast(Sequence[float], cum_weights)
            )
            length_index, rule_index = divmod(index, len(binary_rule_distribution.rules))
            B_length = length_index + 1
            B, C = binary_rule_distribution.rules[rule_index]
            # Concatenate the results from the recursive calls using linked
            # lists so that the concatenation is done in constant time.
            result = self.sample_from_variable(B, B_length, generator)
            result.extend(self.sample_from_variable(C, length - B_length, generator))
            return result
